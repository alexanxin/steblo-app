#!/usr/bin/env node
// Writes public/src/lt-tables.js: one robust-soliton degree table per transfer size class, as
// integers, so two phones never disagree on a degree through floating-point rounding.
// Usage: node scripts/lt-tables.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";

const C = 0.05, DELTA = 0.5, MAX_DEGREE = 64, TOP = 4294967295;
const CLASSES = [16, 32, 64, 128, 256, 512, 1024, 2048, 4096, 8192, 16384];

function table(k) {
  const r = C * Math.log(k / DELTA) * Math.sqrt(k), spike = Math.floor(k / r), p = [];
  for (let d = 1; d <= Math.min(k, MAX_DEGREE); d++) {
    const rho = d === 1 ? 1 / k : 1 / (d * (d - 1));
    const tau = d < spike ? r / (d * k) : d === spike ? r * Math.log(r / DELTA) / k : 0;
    p.push(rho + tau);
  }
  const total = p.reduce((a, b) => a + b);
  let sum = 0;
  const cdf = p.map(x => Math.floor((sum += x) / total * TOP));
  cdf[cdf.length - 1] = TOP;
  return cdf;
}

export function render() {
  const rows = CLASSES.map(k => `  { k: ${k}, cdf: [${table(k).join(", ")}] },`).join("\n");
  return `// Generated by scripts/lt-tables.mjs; don't edit. Robust soliton (c = ${C}, δ = ${DELTA}), degrees 1 to\n// ${MAX_DEGREE}, one table per transfer size class. Degree d is the first d with draw <= cdf[d - 1].\nexport const TABLES = [\n${rows}\n];\n`;
}

const out = new URL("../public/src/lt-tables.js", import.meta.url);
if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  if (process.argv[2] === "--check") process.exit(readFileSync(out, "utf8") === render() ? 0 : 1);
  writeFileSync(out, render());
}
